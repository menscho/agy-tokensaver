def _img_dims(path: str) -> tuple[int, int]:
    try:
        with open(path, "rb") as fh:
            buf = fh.read(32768)
    except OSError:
        return 0, 0
    n = len(buf)
    if n < 24:
        return 0, 0
    if buf[:8] == b"\x89PNG\r\n\x1a\n" and buf[12:16] == b"IHDR":
        w, h = struct.unpack(">II", buf[16:24])
        return int(w), int(h)
    if buf[:2] == b"\xff\xd8":
        pos = 2
        while pos + 9 < n:
            if buf[pos] != 0xFF:
                break
            m = buf[pos + 1]
            pos += 2
            if m in (0xFF, 0x00, 0x01) or (0xD0 <= m <= 0xD9):
                continue
            seg_len = struct.unpack(">H", buf[pos : pos + 2])[0]
            if seg_len < 2 or pos + seg_len > n:
                break
            if m in (0xC0, 0xC1, 0xC2):
                h, w = struct.unpack(">HH", buf[pos + 3 : pos + 7])
                return int(w), int(h)
            pos += seg_len
    return 0, 0


def _fnv1a_32_str(s: str) -> int:
    h = 2166136261
    for ch in s:
        h = ((h ^ ord(ch)) * 16777619) & 0xFFFFFFFF
    return h


def _fnv1a_32_bytes(b: bytes) -> str:
    h = 2166136261
    for byte in b:
        h = ((h ^ byte) * 16777619) & 0xFFFFFFFF
    return f"{h:08x}"


def _handle_media(doc: dict[str, Any], ti: dict[str, Any], path: str, check_path: str, plugin_root: str) -> None:
    if IMAGE_DEDUP_RE.search(check_path):
        cid = get_str(doc, "conversationId") or ""
        tx = get_str(doc, "transcriptPath") or ""
        step = get_int(doc, "stepIdx")
        dd = data_dir(plugin_root)
        scid = safe_cid(cid)
        try:
            st = os.stat(path)
            isz, imt = int(st.st_size), int(st.st_mtime)
        except OSError:
            isz, imt = 0, 0

        if cid and step is not None and isz > 0:
            idir = os.path.join(dd, "reads")
            idup = os.path.join(idir, f"{scid}.imgdup")
            ikey = f"{check_path}\t{imt}\t{isz}"
            kept_i: list[str] = []
            dup_step: int | None = None
            if os.path.isfile(idup):
                try:
                    with open(idup, "r", encoding="utf-8", errors="replace") as dfh:
                        for ln in dfh:
                            ln = ln.rstrip("\r\n")
                            parts = ln.split("\t", 1)
                            if len(parts) < 2:
                                continue
                            try:
                                st_n = int(parts[0])
                            except ValueError:
                                continue
                            if parts[1] == ikey and step >= st_n and (step - st_n) <= 16:
                                dup_step = st_n
                            if step - st_n <= 40:
                                kept_i.append(ln)
                except OSError:
                    pass
            if dup_step is not None:
                ib = re.sub(r"^.*[/\\]", "", check_path)
                emit_deny(f"[token-saver] Image '{ib}' is unchanged and still in context from step {dup_step} (~1.5k vision tok/turn saved).")
                return
            try:
                os.makedirs(idir, exist_ok=True)
                kept_i.append(f"{step}\t{ikey}")
                kept_i = kept_i[-40:]
                with open(idup, "w", encoding="utf-8") as wfh:
                    wfh.write("\n".join(kept_i) + "\n")
            except OSError:
                pass

        if cid and tx and os.path.isfile(tx):
            try:
                if os.path.getsize(tx) > 153600:
                    idir = os.path.join(dd, "reads")
                    ifile = os.path.join(idir, f"{scid}.imgcnt")
                    cnt = 0
                    if os.path.isfile(ifile):
                        with open(ifile, "r", encoding="utf-8", errors="replace") as ifh:
                            cnt = int((ifh.readline() or "0").strip() or "0")
                    cnt += 1
                    if cnt > 3:
                        emit_deny(
                            f"[token-saver] Image #{cnt} in a long session (>150KB transcript; each image replays ~1.5K tok/turn). "
                            "Inspect only necessary frames or delegate multi-image work to a separate subagent."
                        )
                        return
                    os.makedirs(idir, exist_ok=True)
                    with open(ifile, "w", encoding="utf-8") as ofh:
                        ofh.write(f"{cnt}\n")
            except Exception:
                pass

        if read_compact_reads(plugin_root) and RASTER_RESIZE_RE.search(check_path) and isz > 65536:
            iw, ih = _img_dims(path)
            if iw > 1568 or ih > 1568:
                tmpb = (os.environ.get("TMPDIR") or os.environ.get("TEMP") or os.environ.get("TMP") or tempfile.gettempdir()).rstrip("/\\")
                ut_raw = os.environ.get("USERNAME", "user") if os.name == "nt" else str(os.getuid() if hasattr(os, "getuid") else "user")
                ut = re.sub(r"[^A-Za-z0-9_-]", "_", ut_raw)
                sdir = os.path.join(tmpb, f"agy-tokensaver-{ut}")
                try:
                    os.makedirs(sdir, mode=0o700, exist_ok=True)
                except OSError:
                    pass
                h = _fnv1a_32_str(f"{path}|{imt}|{isz}")
                dst = os.path.join(sdir, f"img-{h:08x}.jpg")
                if not os.path.isfile(dst):
                    cmds: list[list[str]] = [
                        ["ffmpeg", "-v", "error", "-y", "-i", path, "-vf", "scale='min(1280,iw)':'min(1280,ih)':force_original_aspect_ratio=decrease", "-q:v", "4", dst],
                        ["magick", path, "-resize", "1280x1280>", "-quality", "85", dst],
                    ]
                    if os.uname().sysname == "Darwin" if hasattr(os, "uname") else False:
                        cmds.insert(1, ["sips", "-Z", "1280", "-s", "format", "jpeg", path, "--out", dst])
                    for cmd in cmds:
                        try:
                            p = subprocess.run(cmd, capture_output=True, timeout=4)
                            if p.returncode == 0 and os.path.isfile(dst) and os.path.getsize(dst) > 0:
                                break
                        except Exception:
                            continue
                if os.path.isfile(dst) and os.path.getsize(dst) > 0:
                    key = "AbsolutePath" if get_str(ti, "AbsolutePath") is not None else "Path"
                    emit_allow({key: dst})
                    return
    emit_allow()


class ReadGuard:
    """Encapsulates state for one PreToolUse read_file/view_file invocation."""

    def __init__(self, doc: dict[str, Any], ti: dict[str, Any], path: str, check_path: str, plugin_root: str) -> None:
        self.doc = doc
        self.ti = ti
        self.path = path
        self.check_path = check_path
        self.plugin_root = plugin_root
        st = os.stat(path)
        self.size = int(st.st_size)
        self.mtime = int(st.st_mtime)
        self.base = re.sub(r"^.*[/\\]", "", check_path)
        self.kb = f"{self.size / 1024:.1f}"
        self.start = get_int(ti, "StartLine")
        self.end = get_int(ti, "EndLine")
        self.has_both = self.start is not None and self.end is not None and self.end >= self.start
        self.span = (self.end - self.start + 1) if (self.has_both and self.end is not None and self.start is not None) else 0
        self.dup_step = get_int(doc, "stepIdx")
        self.dup_cid = get_str(doc, "conversationId") or ""
        self.scid = safe_cid(self.dup_cid)
        self.pk = path_key(path)
        self.dedupe_on = bool(self.size > 4096 and self.dup_step is not None and self.dup_cid and not re.search(r"[\t\r\n]", path))
        self.compact_reads = read_compact_reads(plugin_root)
        self.is_prose = bool(PROSE_RE.search(self.base))
        self.is_spillback = bool(SPILLBACK_RE.search(check_path.replace("\\", "/")))

        self._scanned = False
        self.file_lines: int | None = None
        self.file_md5: str | None = None
        self.line_len: list[int] = []
        self._hist_loaded = False
        self.hist_lines: list[str] = []
        self._epoch: int | None = None
        self._tx_state: tuple[bool, int] | None = None
        self.est_lines = 1
        self.avg_line = 80.0
        self.lic_skip_lines = 0

    def measure_line_range(self, req_s: int | None, req_e: int | None) -> tuple[bool, int, int | None, bool]:
        s = req_s if (req_s is not None and req_s >= 1) else 1
        has_e = req_e is not None
        e = int(req_e) if req_e is not None else (s + READ_MAX_LINES - 1)
        if e - s + 1 > READ_MAX_LINES:
            e = s + READ_MAX_LINES - 1
        if e < s:
            return False, 0, None, False
        if self.size > MAX_SCAN_BYTES and s > 1:
            return False, READ_MAX_BYTES, None, False
        try:
            with open(self.path, "rb") as fh:
                ln = slice_bytes = scanned = 0
                hit_trunc = False
                safe_end: int | None = None
                reached_eof = False
                while True:
                    line = fh.readline()
                    if not line:
                        reached_eof = True
                        break
                    ln += 1
                    llen = len(line)
                    scanned += llen
                    if ln < s:
                        if scanned > MAX_SCAN_BYTES:
                            return False, READ_MAX_BYTES, None, False
                        continue
                    if ln > e:
                        break
                    slice_bytes += llen
                    eff_fmt = slice_bytes + (ln - s + 1) * 12
                    if not hit_trunc and eff_fmt <= SAFE_DELIV_BYTES:
                        safe_end = ln
                    else:
                        hit_trunc = True
                    if slice_bytes >= READ_MAX_BYTES:
                        slice_bytes = READ_MAX_BYTES
                        hit_trunc = True
                        break
                full_file = bool(s == 1 and not has_e and reached_eof and not hit_trunc and ln <= READ_MAX_LINES)
                return True, slice_bytes, safe_end, full_file
        except OSError:
            return False, 0, None, False

    def deny(self, cat: str, msg: str, raw_override: int | None = None) -> None:
        if raw_override is None and (self.start is not None or self.end is not None):
            ok, sb, _, _ = self.measure_line_range(self.start, self.end)
            if ok:
                raw_override = sb
        eff_raw = raw_override if raw_override is not None else min(self.size, READ_MAX_BYTES)
        eff_raw = max(0, min(READ_MAX_BYTES, eff_raw))
        kept = len(msg.encode("utf-8", errors="replace"))
        log_event(
            self.plugin_root,
            "read_guard",
            cat,
            "blocked",
            eff_raw,
            kept,
            int((eff_raw - kept) / 4),
            self.base,
            session_id=self.dup_cid,
            file_bytes=self.size,
        )
        emit_deny(msg)

    def scan_file(self) -> None:
        if self._scanned:
            return
        self._scanned = True
        if self.size > MAX_SCAN_BYTES:
            return
        try:
            with open(self.path, "rb") as fh:
                data = fh.read()
        except OSError:
            return
        if len(data) != self.size:
            return
        lines = data.splitlines(keepends=True)
        self.line_len = [len(x) for x in lines]
        self.file_lines = len(self.line_len)
        self.file_md5 = hashlib.md5(data).hexdigest()

    def native_bytes(self, s: int, e: int) -> int:
        tot = n = 0
        max_l = len(self.line_len)
        for i in range(s, e + 1):
            n += 1
            if i > max_l or n > READ_MAX_LINES:
                break
            tot += self.line_len[i - 1] + len(str(i)) + 2
            if tot >= READ_MAX_BYTES:
                return READ_MAX_BYTES
        return tot

    def load_hist(self) -> None:
        if self._hist_loaded:
            return
        self._hist_loaded = True
        rdir = os.path.join(data_dir(self.plugin_root), "reads")
        rfile = os.path.join(rdir, f"{self.scid}.tsv")
        init_steps = get_int(self.doc, "initialNumSteps")
        if init_steps is not None and init_steps >= 0 and self.scid:
            ifile = os.path.join(rdir, f"{self.scid}.initsteps")
            prev_init: int | None = None
            if os.path.isfile(ifile):
                try:
                    with open(ifile, "r", encoding="utf-8", errors="replace") as ifh:
                        raw_i = ifh.readline().strip()
                        if raw_i:
                            prev_init = int(raw_i)
                except Exception:
                    prev_init = None
            if prev_init is not None and prev_init >= 0 and init_steps < prev_init:
                for p in (rfile, os.path.join(rdir, f"{self.scid}.searches"), os.path.join(rdir, f"{self.scid}.lastblk")):
                    try:
                        os.unlink(p)
                    except OSError:
                        pass
            try:
                os.makedirs(rdir, exist_ok=True)
                with open(ifile, "w", encoding="utf-8") as wfh:
                    wfh.write(f"{init_steps}\n")
            except OSError:
                pass
        if os.path.isfile(rfile):
            try:
                with open(rfile, "r", encoding="utf-8", errors="replace") as rfh:
                    self.hist_lines = [ln.rstrip("\r\n") for ln in rfh if ln.rstrip("\r\n")]
            except OSError:
                pass

    def cur_epoch(self) -> int:
        if self._epoch is not None:
            return self._epoch
        self._epoch = 0
        ep_file = os.path.join(data_dir(self.plugin_root), "alerts", f"{self.scid}.epoch")
        if os.path.isfile(ep_file):
            try:
                with open(ep_file, "r", encoding="utf-8", errors="replace") as efh:
                    self._epoch = int((efh.readline() or "0").strip() or "0")
            except Exception:
                self._epoch = 0
        return self._epoch

    def transcript_state(self) -> tuple[bool, int]:
        if self._tx_state is not None:
            return self._tx_state
        res = (False, -1)
        try:
            tx = get_str(self.doc, "transcriptPath") or ""
            f = tx if (tx and os.path.isfile(tx)) else None
            if f is None and re.match(r"^[A-Za-z0-9_-]+$", self.dup_cid):
                home = os.environ.get("HOME") or os.environ.get("USERPROFILE") or ""
                for app in ("antigravity", "antigravity-cli"):
                    cand = os.path.join(home, ".gemini", app, "brain", self.dup_cid, ".system_generated", "logs", "transcript.jsonl")
                    if os.path.isfile(cand):
                        f = cand
                        break
            if f is not None:
                fsz = os.path.getsize(f)
                if 0 < fsz <= 32 * 1024 * 1024 and self.dup_step is not None:
                    barrier = -1
                    prev_ctx: int | None = None
                    pl_step: int | None = None
                    pl_names: list[str] = []
                    with open(f, "rb") as fh:
                        for bline in fh:
                            m_si = re.match(rb'^\{\s*"step_index"\s*:\s*"?(\d+)', bline)
                            if not m_si:
                                continue
                            si = int(m_si.group(1))
                            if si >= self.dup_step:
                                break
                            if b'"CHECKPOINT"' not in bline and b'"PLANNER_RESPONSE"' not in bline:
                                continue
                            try:
                                rec = json.loads(bline.decode("utf-8", errors="replace")) if b"{" in bline else None
                            except Exception:
                                rec = None
                            if not isinstance(rec, dict):
                                continue
                            rtype = rec.get("type")
                            if rtype == "CHECKPOINT":
                                barrier, prev_ctx, pl_step, pl_names = si, None, None, []
                            elif rtype == "PLANNER_RESPONSE":
                                pl_step = si
                                tcs = rec.get("tool_calls")
                                pl_names = [str(tc.get("name", "")) for tc in tcs if isinstance(tc, dict)] if isinstance(tcs, list) else []
                                in_t = get_int(rec, "input_tokens")
                                if in_t is not None:
                                    ctx = in_t + (get_int(rec, "cache_read_tokens") or 0)
                                    if prev_ctx is not None and prev_ctx >= 20000 and ctx < prev_ctx * 0.6:
                                        barrier = si
                                    if ctx > 0:
                                        prev_ctx = ctx
                    if pl_step is not None:
                        k = self.dup_step - pl_step
                        if 1 <= k <= len(pl_names) and pl_names[k - 1] in ("read_file", "view_file"):
                            res = (True, barrier)
        except Exception:
            pass
        self._tx_state = res
        return res

    def dedupe_plan(self, S: int, E: int) -> tuple[Any, ...]:
        if not self.dedupe_on or E < S or self.dup_step is None:
            return ("none",)
        self.load_hist()
        ep = self.cur_epoch()
        cand: list[tuple[int, int, int, int, str]] = []
        for rl in self.hist_lines:
            parts = rl.split("\t")
            if len(parts) < 8:
                continue
            rp, rs, re_s, rm, rsz, rst, rep, rmd = parts[:8]
            try:
                if rp != self.pk or int(rm) != self.mtime or int(rsz) != self.size or int(rep) != ep:
                    continue
                step_r = int(rst)
            except ValueError:
                continue
            d = self.dup_step - step_r
            if d <= 0:
                continue
            lo = 1 if rs == "" else int(rs)
            hi = 10**12 if re_s == "" else int(re_s)
            cand.append((lo, hi, step_r, d, rmd))
        if not cand:
            return ("none",)
        self.scan_file()
        if not self.file_md5:
            return ("none",)
        cand = [c for c in cand if c[4] == self.file_md5]
        if not cand:
            return ("none",)
        tx_ok, barrier = self.transcript_state()
        cand = [c for c in cand if (c[2] > barrier if tx_ok else c[3] <= NEAR_STEPS)]
        if not cand:
            return ("none",)
        gaps: list[tuple[int, int]] = []
        cur = S
        for lo, hi, _, _, _ in sorted(cand, key=lambda x: x[0]):
            if hi < cur:
                continue
            if lo > E:
                break
            if lo > cur:
                gaps.append((cur, lo - 1))
            if hi + 1 > cur:
                cur = hi + 1
            if cur > E:
                break
        if cur <= E:
            gaps.append((cur, E))
        if not gaps:
            covering = [c for c in cand if c[0] <= S and c[1] >= E]
            if covering:
                best = min(covering, key=lambda x: x[3])
                rng = "" if best[1] >= 10**12 else f":{best[0]}-{best[1]}"
                return ("dup", f"your read of '{self.base}{rng}' at step {best[2]}")
            last = min(cand, key=lambda x: x[3])
            return ("dup", f"your earlier reads of '{self.base}' (last at step {last[2]})")
        if len(gaps) > 1:
            return ("none",)
        ga, gb = gaps[0]
        if ga == S and gb == E:
            return ("none",)
        if gb - ga + 1 > READ_MAX_LINES:
            gb = ga + READ_MAX_LINES - 1
        saved = self.native_bytes(S, E) - self.native_bytes(ga, gb)
        if saved < TRIM_MIN_BYTES:
            return ("none",)
        return ("trim", ga, gb, saved)

    def record_read(self, eff_s: int | None, eff_e: int | None) -> None:
        if not self.dedupe_on or self.dup_step is None:
            return
        try:
            self.scan_file()
            if not self.file_md5:
                return
            mok, _, safe_end, full_file = self.measure_line_range(eff_s, eff_e)
            if not mok:
                return
            if full_file:
                rec_s, rec_e = "", ""
            elif safe_end is not None:
                rs_eff = eff_s if (eff_s is not None and eff_s >= 1) else 1
                if safe_end < rs_eff:
                    return
                rec_s, rec_e = str(rs_eff), str(safe_end)
            else:
                return
            self.load_hist()
            self.hist_lines.append(
                "\t".join([self.pk, rec_s, rec_e, str(self.mtime), str(self.size), str(self.dup_step), str(self.cur_epoch()), self.file_md5])
            )
            self.hist_lines = self.hist_lines[-HIST_MAX:]
            rdir = os.path.join(data_dir(self.plugin_root), "reads")
            os.makedirs(rdir, exist_ok=True)
            with open(os.path.join(rdir, f"{self.scid}.tsv"), "w", encoding="utf-8") as wfh:
                wfh.write("\n".join(self.hist_lines) + "\n")
        except Exception:
            pass

    def _snap_path(self) -> str:
        h = _fnv1a_32_str(self.pk)
        return os.path.join(data_dir(self.plugin_root), "reads", "snaps", f"{h:08x}.lines")

    def save_line_snap(self) -> None:
        if not self.dedupe_on or not (4096 < self.size <= 65536):
            return
        if self.file_lines is None or self.file_lines <= 160 or not self.file_md5:
            return
        if self.is_spillback or SNAP_SKIP_EXT_RE.search(self.base):
            return
        try:
            sdir = os.path.join(data_dir(self.plugin_root), "reads", "snaps")
            os.makedirs(sdir, exist_ok=True)
            with open(self.path, "rb") as fh:
                hashes = [_fnv1a_32_bytes(ln) for ln in fh]
            with open(self._snap_path(), "wb") as wfh:
                wfh.write((self.file_md5 + "\n" + "\n".join(hashes) + "\n").encode("utf-8"))
        except OSError:
            pass

    def dirty_hunk_range(self) -> tuple[int, int] | None:
        if not self.dedupe_on or self.start is not None or self.end is not None or not (4096 < self.size <= 65536):
            return None
        if self.file_lines is None or self.file_lines <= 180 or not self.file_md5:
            return None
        if self.is_spillback or SNAP_SKIP_EXT_RE.search(self.base):
            return None
        sp = self._snap_path()
        if not os.path.isfile(sp):
            return None
        try:
            with open(sp, "rb") as sfh:
                old_lines_b = sfh.read().splitlines()
            if not old_lines_b:
                return None
            old_md5 = old_lines_b[0].decode("utf-8", errors="replace")
            if old_md5 == self.file_md5:
                return None
            old_h = [x.decode("utf-8", errors="replace") for x in old_lines_b[1:]]
            if not old_h:
                return None
            with open(self.path, "rb") as cfh:
                cur_h = [_fnv1a_32_bytes(ln) for ln in cfh]
        except OSError:
            return None
        n_old, n_cur = len(old_h), len(cur_h)
        pre = 0
        while pre < n_old and pre < n_cur and old_h[pre] == cur_h[pre]:
            pre += 1
        suf = 0
        while suf < (n_old - pre) and suf < (n_cur - pre) and old_h[n_old - 1 - suf] == cur_h[n_cur - 1 - suf]:
            suf += 1
        lo = pre + 1
        hi = max(lo, n_cur - suf)
        span_dirty = hi - lo + 1
        if span_dirty <= 0 or span_dirty > 80 or n_cur < 180:
            return None
        a0 = max(1, lo - 15)
        b0 = min(n_cur, hi + 15)
        if (b0 - a0 + 1) >= n_cur - 40:
            return None
        return a0, b0

    def _worth_cap(self, want_lines: int, cap_lines: int) -> bool:
        native_lines = min(READ_MAX_LINES, want_lines)
        native_bytes = min(float(READ_MAX_BYTES), native_lines * self.avg_line)
        return (native_bytes - cap_lines * self.avg_line) >= 1024

    def decide_and_emit(self, cap: int | None, cat_label: str | None) -> None:
        a: int | None = None
        b: int | None = None
        trim_saved = 0
        cap_lab: str | None = None
        if self.dedupe_on:
            self.scan_file()
            S = self.start if (self.start is not None and self.start >= 1) else 1
            E = int(self.end) if self.end is not None else (S + READ_MAX_LINES - 1)
            if E - S + 1 > READ_MAX_LINES:
                E = S + READ_MAX_LINES - 1
            if self.file_lines is not None and E > self.file_lines:
                E = self.file_lines
            try:
                p = self.dedupe_plan(S, E)
            except Exception:
                p = ("none",)
            if p[0] == "dup":
                req = f":{self.start if self.start is not None else ''}-{self.end if self.end is not None else ''}" if (self.start is not None or self.end is not None) else ""
                mok, sb, _, _ = self.measure_line_range(self.start, self.end)
                self.deny(
                    "duplicate_read",
                    f"[token-saver] '{self.base}{req}' is unchanged and still in context from {p[1]}. Reuse that; no re-read needed.",
                    sb if mok else None,
                )
                return
            if p[0] == "trim":
                a, b, trim_saved = int(p[1]), int(p[2]), int(p[3])
            if a is None:
                try:
                    dh = self.dirty_hunk_range()
                    if dh is not None:
                        a, b = dh
                        cap_lab = "dirty_hunk"
                except Exception:
                    pass

        if cap is not None and cap_lab is None and cat_label is not None:
            s0 = a if a is not None else (self.start if (self.start is not None and self.start >= 1) else 1)
            if self.start is None and self.end is None and a is None and self.lic_skip_lines >= 12 and not self.is_spillback and not self.is_prose:
                s0 = self.lic_skip_lines + 1
            total = self.file_lines if self.file_lines is not None else self.est_lines
            want_end: int | None = None
            c = cap
            lab = cat_label
            if self.end is None:
                want_end = total
                lab = f"{cat_label}_open_end" if self.start is not None else cat_label
            elif self.start is None and self.is_spillback:
                want_end = b if b is not None else min(self.end, total)
                lab = f"{cat_label}_open_start"
            elif self.start is not None and self.is_spillback and self.span > 220:
                e2 = b if b is not None else self.end
                want_end = min(e2, total)
                c = 220
                lab = f"{cat_label}_wide_span"

            if want_end is not None:
                rem = want_end - s0 + 1
                if rem > c + 60 and self._worth_cap(rem, c):
                    if self.start is None and self.end is None and a is None and (self.is_spillback or LOG_EXT_RE.search(self.base)) and total > c:
                        ts = max(1, total - c + 1)
                        a, b, cap_lab = ts, total, f"{lab}_tail"
                    else:
                        a, b, cap_lab = s0, s0 + c - 1, lab

        if a is not None and b is not None:
            mok, sb, _, _ = self.measure_line_range(self.start, self.end) if (self.start is not None or self.end is not None) else (False, 0, None, False)
            kok, kb2, _, _ = self.measure_line_range(a, b)
            raw_b = sb if mok else min(self.size, READ_MAX_BYTES)
            kept_b = (kb2 if kok else 0) + OVERWRITE_NOTICE
            cat = (f"{cap_lab}+overlap_trim" if trim_saved else cap_lab) if cap_lab else "overlap_trim"
            log_event(
                self.plugin_root,
                "read_guard",
                cat,
                "capped" if cap_lab else "trimmed",
                raw_b,
                kept_b,
                int((raw_b - kept_b) / 4),
                self.base,
                session_id=self.dup_cid,
                file_bytes=self.size,
            )
            self.record_read(a, b)
            self.save_line_snap()
            emit_allow({"StartLine": a, "EndLine": b})
            return

        self.record_read(self.start, self.end)
        self.save_line_snap()
        emit_allow()


def main() -> int:
    plugin_root = script_plugin_root(__file__)
    raw = read_stdin_capped()
    doc = decode_hook_input(raw)
    if doc is None or hooks_disabled(plugin_root):
        emit_allow()
        return 0

    ti = tool_input(doc)
    boff = get_int(ti, "ByteOffset", "ContentOffset")
    if boff is not None and boff > 0:
        emit_allow()
        return 0

    path = get_str(ti, "Path", "AbsolutePath")
    if not path:
        emit_allow()
        return 0
    path = resolve_path(path, doc, ti)
    if not os.path.isfile(path):
        emit_allow()
        return 0

    check_path = path
    try:
        if os.path.islink(path):
            target = os.readlink(path)
            if target:
                if not re.match(r"^(?:/|[A-Za-z]:[/\\]|\\\\)", target):
                    target = os.path.join(os.path.dirname(path), target)
                check_path = target
    except OSError:
        pass

    if MEDIA_EXT_RE.search(check_path):
        _handle_media(doc, ti, path, check_path, plugin_root)
        return 0

    try:
        rg = ReadGuard(doc, ti, path, check_path, plugin_root)
    except OSError:
        emit_allow()
        return 0

    head_nul = False
    if rg.size > 0:
        try:
            with open(path, "rb") as hfh:
                hb = hfh.read(4096)
            head_nul = b"\x00" in hb
        except OSError:
            pass

    inspect_py = os.path.join(plugin_root, "scripts", "ts_inspect.py")
    sh_path = esc_sh(path)
    eff_tok = min(rg.size, READ_MAX_BYTES) // 4

    if SQLITE_RE.search(rg.base) and head_nul:
        rg.deny("sqlite", f"[token-saver] Blocked read of SQLite DB '{rg.base}' ({rg.kb}KB). Run: python3 {inspect_py} sqlite {sh_path}")
        return 0
    if BIN_EXT_RE.search(rg.base) or (AMBIG_BIN_RE.search(rg.base) and head_nul):
        rg.deny("binary", f"[token-saver] Blocked read of binary file '{rg.base}' ({rg.kb}KB). Use targeted CLI tools (file/strings/python3) instead of read_file.")
        return 0

    if rg.size <= 4096:
        if head_nul:
            rg.deny("binary", f"[token-saver] Blocked read of binary file '{rg.base}' ({rg.kb}KB). Use file/strings/python3 instead.")
            return 0
        emit_allow()
        return 0

    if rg.size <= 12288 and not (rg.size > 8192 and SMALL_DATA_DOC_RE.search(rg.base)):
        if head_nul:
            rg.deny("binary", f"[token-saver] Blocked read of binary file '{rg.base}' ({rg.kb}KB). Use file/strings/python3 instead.")
            return 0
        rg.decide_and_emit(None, None)
        return 0

    peek_n = peek_nl = max_line = ws_on_max = 0
    has_nul = has_b64 = has_gen_hdr = False
    try:
        with open(path, "rb") as fh:
            buf = fh.read(16384)
        peek_n = len(buf)
        if peek_n > 0:
            has_nul = b"\x00" in buf
            peek_nl = buf.count(b"\n")
            has_b64 = bool(B64_RE.search(buf))
            ptxt = buf.decode("utf-8", errors="replace")
            plines = re.split(r"\r?\n|\r", ptxt)
            for pl in plines:
                if len(pl) > max_line:
                    max_line = len(pl)
                    ws_on_max = pl.count(" ") + pl.count("\t")
            has_gen_hdr = bool(GEN_HDR_RE.search("\n".join(plines[:16])))
            in_blk = saw_lic = False
            c_end = 0
            for li, x in enumerate(plines[:56]):
                if li == 0 and x.startswith("#!"):
                    c_end = 1
                    continue
                if in_blk:
                    if LIC_RE.search(x):
                        saw_lic = True
                    c_end = li + 1
                    if "*/" in x:
                        in_blk = False
                    continue
                if re.match(r"^\s*/\*", x):
                    if LIC_RE.search(x):
                        saw_lic = True
                    c_end = li + 1
                    if "*/" not in x:
                        in_blk = True
                    continue
                if re.match(r"^\s*(?://|#|--)\s?", x) or re.match(r"^\s*$", x):
                    if LIC_RE.search(x):
                        saw_lic = True
                    c_end = li + 1
                    continue
                break
            if saw_lic and 12 <= c_end <= 55:
                rg.lic_skip_lines = c_end
    except OSError:
        pass

    if has_nul:
        rg.deny("binary", f"[token-saver] Blocked read of binary file '{rg.base}' ({rg.kb}KB). Use file/strings/python3 instead.")
        return 0

    if rg.base.lower().endswith(".ipynb") and (not rg.has_both or rg.span > 120):
        rg.deny("ipynb", f"[token-saver] Blocked raw read of notebook '{rg.base}' ({rg.kb}KB; JSON/base64 bloat). Run: python3 {inspect_py} ipynb {sh_path}")
        return 0
    if rg.base.lower().endswith(".svg") and rg.size > 20480 and (not rg.has_both or rg.span > 80):
        rg.deny("svg", f"[token-saver] Blocked raw read of large SVG '{rg.base}' ({rg.kb}KB). Run: python3 {inspect_py} svg {sh_path} (or pass StartLine/EndLine <=80).")
        return 0
    if rg.base.lower().endswith(".har") and (not rg.has_both or rg.span > 100):
        rg.deny("har", f"[token-saver] Blocked raw read of HAR '{rg.base}' ({rg.kb}KB). Run: python3 {inspect_py} har {sh_path}")
        return 0

    if rg.size > 15360 and not rg.is_spillback and not (rg.has_both and rg.span <= 150):
        if has_b64:
            rg.deny("base64_blob", f"[token-saver] Blocked read of '{rg.base}' ({rg.kb}KB) containing inline base64 data URI. Use grep or python3 to inspect non-blob parts.")
            return 0
        if rg.is_prose:
            if max_line > 6000 or (max_line > 2500 and (ws_on_max / max_line) < 0.05):
                rg.deny("single_line_minified", f"[token-saver] Blocked read of single-line/dense file '{rg.base}' ({rg.kb}KB). Use grep/python3 to extract needed parts.")
                return 0
        elif max_line > 2200:
            rg.deny("single_line_minified", f"[token-saver] Blocked read of single-line/minified file '{rg.base}' ({rg.kb}KB, max line {max_line}B). Extract needed keys/snippets with python3/grep or inspect.py.")
            return 0

    if ARTIFACT_RE.search(rg.base) and rg.size > 16384 and (not rg.has_both or rg.span > 100):
        rg.deny("artifact_dump", f"[token-saver] Blocked unbounded read of large artifact '{rg.base}' ({rg.kb}KB). Use python3 {inspect_py} json {sh_path} or grep.")
        return 0
    if LOCKFILE_RE.match(rg.base) and (not rg.has_both or rg.span > 150):
        rg.deny("lockfile", f"[token-saver] Blocked unbounded read of lockfile '{rg.base}' ({rg.kb}KB, ~{eff_tok} tok). Inspect the manifest, grep for a package, or pass StartLine/EndLine <=150.")
        return 0
    if GEN_ARTIFACT_RE.search(rg.base) and (not rg.has_both or rg.span > 120):
        rg.deny("generated_artifact", f"[token-saver] Blocked unbounded read of generated artifact '{rg.base}' ({rg.kb}KB). Read original source files or use grep.")
        return 0

    if rg.size > 24576 and (not rg.has_both or rg.span > 150):
        cpath_s = check_path.replace("\\", "/")
        if GEN_CODE_RE.search(rg.base) or PRISMA_RE.search(cpath_s):
            rg.deny("generated_code", f"[token-saver] Blocked unbounded read of generated file '{rg.base}' ({rg.kb}KB). Read the schema/source, grep for the symbol, or pass StartLine/EndLine <=150.")
            return 0
        if rg.base.lower().endswith(".d.ts") and rg.size > 51200:
            rg.deny("large_dts", f"[token-saver] Blocked unbounded read of huge type def '{rg.base}' ({rg.kb}KB). Grep for the symbol and read a <=150-line slice.")
            return 0
        if OPENAPI_RE.search(rg.base) and rg.size > 65536:
            rg.deny("large_schema", f"[token-saver] Blocked unbounded read of huge schema '{rg.base}' ({rg.kb}KB). Run: python3 {inspect_py} schema {sh_path}")
            return 0
        if has_gen_hdr and not rg.is_prose and not rg.is_spillback:
            rg.deny("generated_header", f"[token-saver] Blocked unbounded read of auto-generated file '{rg.base}' ({rg.kb}KB; @generated/DO NOT EDIT header). Run: python3 {inspect_py} outline {sh_path} or grep.")
            return 0
    if rg.size > 24576 and (not rg.has_both or rg.span > 150) and not rg.is_prose and VENDOR_RE.search(check_path.replace("\\", "/")):
        rg.deny("vendor_dir", f"[token-saver] Blocked unbounded read inside vendor/build path '{rg.base}' ({rg.kb}KB). Grep for the symbol or pass StartLine/EndLine <=150.")
        return 0

    exact_lines: int | None = None
    if rg.size <= 49152:
        try:
            with open(path, "rb") as fh2:
                all_b = fh2.read(49152)
            if all_b:
                exact_lines = all_b.count(b"\n") + 1
        except OSError:
            pass
    rg.est_lines = exact_lines if exact_lines is not None else (int(rg.size / (peek_n / peek_nl)) if peek_nl > 0 else (rg.size // 80))
    rg.avg_line = rg.size / (rg.est_lines or 1)

    is_data = bool(DATA_EXT_RE.search(rg.base))
    is_log = bool(LOG_EXT_RE.search(rg.base))
    cr = rg.compact_reads
    cap: int | None = None
    cat_label: str | None = None
    if rg.is_spillback and rg.size > 12288:
        avg = (peek_n / peek_nl) if peek_nl > 0 else 80.0
        c = int(12288 / (avg or 80.0))
        cap, cat_label = max(40, min(120, c)), "spillback_log"
    elif is_log and rg.size > 46080:
        cap, cat_label = (100 if cr else 150), "large_log"
    elif is_data and rg.size > (6144 if cr else 8192):
        cap = 80 if cr else (100 if rg.size > 65536 else 120)
        cat_label = "large_data"
    elif not is_log and rg.size > (8192 if cr else 16384):
        if DOC_RE.search(rg.base):
            if cr and CHANGELOG_RE.match(rg.base):
                cap, cat_label = 80, "compact_changelog"
            elif cr and rg.size > 8192:
                cap, cat_label = 120, "compact_doc"
            elif rg.size > 46080:
                cap, cat_label = (200 if rg.size > 102400 else 250), "large_file"
        elif cr and rg.size > 10240:
            if not (exact_lines is not None and exact_lines <= 160 and rg.size <= 12288):
                cap, cat_label = 120, "compact_code"
        elif not cr and not (exact_lines is not None and exact_lines <= 320 and rg.size <= 28672):
            cap, cat_label = (200 if rg.size > 102400 else 250), "large_file"

    rg.decide_and_emit(cap, cat_label)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
